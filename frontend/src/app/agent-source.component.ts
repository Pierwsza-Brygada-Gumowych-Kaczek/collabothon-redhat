import { Component, input } from '@angular/core';
import { DatePipe } from '@angular/common';
import { AgentMeta } from './bank.service';

/** Footer line telling where an agent's output came from. */
@Component({
  selector: 'app-agent-source',
  standalone: true,
  imports: [DatePipe],
  template: `
    @let m = meta();
    @if (m.source === 'demo') {
      <p class="src">
        <span class="dot"></span> Demo content — rule-based recommendations from your account data, not from the AI model
        · {{ m.generated_at | date: 'd MMM yyyy, HH:mm' }}. {{ disclaimer() }}
      </p>
    }
    @if (m.source === 'openshift-ai') {
      <p class="src">
        <span class="dot ai"></span> Generated by the AI model on OpenShift AI ({{ m.model }})
        · {{ m.generated_at | date: 'd MMM yyyy, HH:mm' }}. {{ disclaimer() }}
      </p>
    }
  `,
  styles: `
    .src { color: #6a6e73; font-size: .82rem; line-height: 1.5; }
    .dot { display: inline-block; width: 8px; height: 8px; border-radius: 50%; background: #f0ab00; margin-right: .2rem; }
    .dot.ai { background: #3e8635; }
  `,
})
export class AgentSourceComponent {
  readonly meta = input.required<AgentMeta>();
  readonly disclaimer = input('Prototype — this is not financial advice.');
}
